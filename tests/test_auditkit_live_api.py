"""Real AuditKIT API integration with precomputed *synthetic oracle* outputs.

Tests ONLY interoperability of Sample, custom scorers, native evaluate and
precomputed model. The predictions are not generated by Tiny Aya and must
NEVER be used as evidence of trained-model quality.
"""
import json
from pathlib import Path

import auditkit as ak
from policyproof.core import ROOT, make_gold, read_jsonl
from scripts.auditkit_replay import make_audit_samples, make_scorers


def test_auditkit_replay_evaluates_all_synthetic_gold_predictions():
    rows = read_jsonl(ROOT / "data/unseen_policy_test.jsonl")
    assert len(rows) == 48
    oracle = {
        r["id"]: make_gold(r["expected_answer"], r["expected_source_id"])
        for r in rows
    }
    samples = make_audit_samples(rows, oracle)
    assert len(samples) == 48
    assert all(s.actual_output is not None for s in samples)
    result = ak.evaluate(samples, model="precomputed", scorers=make_scorers(rows))
    assert result.failed_count == 0, result.errors
    assert not result.errors
    assert len(result.predictions) == 48
    assert result.fingerprint
    assert result.headline


def test_auditkit_replay_rejects_nonreal_model_reports():
    from scripts.auditkit_replay import check_saved_outputs
    rows = read_jsonl(ROOT / "data/unseen_policy_test.jsonl")
    fake = {
        "engine": "mock-oracle",
        "is_real_model_result": False,
        "dataset_sha256": "not-a-real-checksum",
        "predictions": [],
    }
    try:
        check_saved_outputs(fake, rows, fake["dataset_sha256"])
    except ValueError as exc:
        assert "genuine" in str(exc)
    else:
        raise AssertionError("Mock results must be rejected by real-model replay validator")
